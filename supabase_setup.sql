CREATE TABLE IF NOT EXISTS public.submissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 120),
    category TEXT NOT NULL CHECK (category IN ('Electronics', 'Mechanical', 'Architecture')),
    condition TEXT NOT NULL CHECK (condition IN ('Like new', 'Good', 'Fair', 'For parts')),
    description TEXT NOT NULL CHECK (length(description) BETWEEN 1 AND 2000),
    contact_name TEXT NOT NULL CHECK (length(contact_name) BETWEEN 1 AND 100),
    email TEXT NOT NULL CHECK (length(email) <= 254),
    phone TEXT NOT NULL CHECK (length(phone) <= 40),
    location TEXT NOT NULL CHECK (length(location) BETWEEN 1 AND 120),
    photos TEXT[] NOT NULL DEFAULT '{}'::text[],
    status TEXT NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'inspection', 'listed', 'closed')),
    grade TEXT CHECK (grade IS NULL OR grade IN ('A', 'B', 'C', 'For parts')),
    listing_type TEXT CHECK (listing_type IS NULL OR listing_type IN ('Sale', 'Rent')),
    asking_price DOUBLE PRECISION CHECK (asking_price IS NULL OR asking_price > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

DO $$
DECLARE
    photos_type TEXT;
BEGIN
    SELECT data_type INTO photos_type
    FROM information_schema.columns
    WHERE table_schema = 'public'
      AND table_name = 'submissions'
      AND column_name = 'photos';

    IF photos_type = 'text' THEN
        ALTER TABLE public.submissions ALTER COLUMN photos DROP DEFAULT;
        ALTER TABLE public.submissions
            ALTER COLUMN photos TYPE TEXT[]
            USING CASE
                WHEN photos IS NULL OR photos = '' THEN '{}'::text[]
                ELSE string_to_array(photos, ',')
            END;
        ALTER TABLE public.submissions ALTER COLUMN photos SET DEFAULT '{}'::text[];
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS public.admin_users (
    user_id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_submissions_status_created
    ON public.submissions (status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_submissions_category_type
    ON public.submissions (category, listing_type);

ALTER TABLE public.submissions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.admin_users ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Public can submit tools" ON public.submissions;
CREATE POLICY "Public can submit tools"
    ON public.submissions FOR INSERT TO anon, authenticated
    WITH CHECK (
        status = 'pending'
        AND grade IS NULL
        AND listing_type IS NULL
        AND asking_price IS NULL
        AND cardinality(photos) <= 3
    );

DROP POLICY IF EXISTS "Admins can view submissions" ON public.submissions;
CREATE POLICY "Admins can view submissions"
    ON public.submissions FOR SELECT TO authenticated
    USING (
        EXISTS (
            SELECT 1 FROM public.admin_users
            WHERE admin_users.user_id = (SELECT auth.uid())
        )
    );

DROP POLICY IF EXISTS "Admins can update submissions" ON public.submissions;
CREATE POLICY "Admins can update submissions"
    ON public.submissions FOR UPDATE TO authenticated
    USING (
        EXISTS (
            SELECT 1 FROM public.admin_users
            WHERE admin_users.user_id = (SELECT auth.uid())
        )
    )
    WITH CHECK (
        EXISTS (
            SELECT 1 FROM public.admin_users
            WHERE admin_users.user_id = (SELECT auth.uid())
        )
        AND (
            status <> 'listed'
            OR (grade IS NOT NULL AND listing_type IS NOT NULL AND asking_price IS NOT NULL)
        )
    );

DROP POLICY IF EXISTS "Admins can read their own access" ON public.admin_users;
CREATE POLICY "Admins can read their own access"
    ON public.admin_users FOR SELECT TO authenticated
    USING (user_id = (SELECT auth.uid()));

REVOKE ALL ON public.submissions FROM PUBLIC, anon, authenticated;
REVOKE ALL ON public.admin_users FROM PUBLIC, anon, authenticated;
GRANT USAGE ON SCHEMA public TO anon, authenticated;
GRANT INSERT ON public.submissions TO anon, authenticated;
GRANT SELECT, UPDATE ON public.submissions TO authenticated;
GRANT SELECT ON public.admin_users TO authenticated;

DO $$
DECLARE
    submissions_sequence REGCLASS;
BEGIN
    submissions_sequence := pg_get_serial_sequence('public.submissions', 'id');
    IF submissions_sequence IS NOT NULL THEN
        EXECUTE format(
            'GRANT USAGE ON SEQUENCE %s TO anon, authenticated',
            submissions_sequence
        );
    END IF;
END $$;

DROP VIEW IF EXISTS public.listings;
CREATE VIEW public.listings WITH (security_invoker = false) AS
SELECT
    id,
    name,
    category,
    condition,
    grade,
    description,
    listing_type,
    asking_price,
    location,
    photos,
    updated_at
FROM public.submissions
WHERE status = 'listed'
  AND grade IS NOT NULL
  AND listing_type IS NOT NULL
  AND asking_price IS NOT NULL;

REVOKE ALL ON public.listings FROM PUBLIC;
GRANT SELECT ON public.listings TO anon, authenticated;

